export interface LawdCodeMatch {
  code: string;
  matchedRegionLabel: string;
}

/**
 * 주소 문자열에서 시/도 + 구 이름을 느슨하게 찾아 LAWD_CD를 매칭한다.
 * 테이블에 없는 지역은 절대 추측하지 않고 null을 반환한다.
 */
export function findLawdCode(address: string): LawdCodeMatch | null {
  const normalized = address.replace(/\s+/g, " ").trim();
  for (const [label, code] of Object.entries(LAWD_CODE_TABLE)) {
    const parts = label.split(" ");
    if (parts.every((p) => normalized.includes(p))) {
      return { code, matchedRegionLabel: label };
    }
  }
  return null;
}
